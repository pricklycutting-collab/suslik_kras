export function milestoneForNewVisit(before, after) {
  return milestones.find((m) => before < m.goal && after >= m.goal) || null;
}
export function backupPayload(records, team = "") {
  return {
    format: "suslik-kras",
    version: 1,
    exportedAt: new Date().toISOString(),
    team,
    visits: [...records.values()],
  };
}
export function validateBackup(data) {
  if (
    !data ||
    data.format !== "suslik-kras" ||
    data.version !== 1 ||
    !Array.isArray(data.visits) ||
    data.visits.length > 24
  )
    throw new Error(
      "Это не резервная копия игры или её версия не поддерживается.",
    );
  if (typeof data.team !== "string" || data.team.length > 40)
    throw new Error("В копии некорректное название команды.");
  const seen = new Set();
  for (const v of data.visits) {
    if (
      !v ||
      !Number.isInteger(v.id) ||
      !locations.some((p) => p.id === v.id) ||
      seen.has(v.id)
    )
      throw new Error("В копии есть неизвестные или повторяющиеся хранители.");
    if (
      typeof v.photo !== "string" ||
      v.photo.length > 3_000_000 ||
      !/^data:image\/jpeg;base64,[A-Za-z0-9+/]+={0,2}$/.test(v.photo) ||
      typeof v.date !== "string" ||
      !Number.isFinite(Date.parse(v.date))
    )
      throw new Error("В копии некорректная фотография или дата.");
    seen.add(v.id);
  }
  return {
    team: data.team,
    visits: data.visits.map((v) => ({
      id: v.id,
      photo: v.photo,
      date: v.date,
    })),
  };
}
