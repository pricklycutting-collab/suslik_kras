export function guardianDialogue(id, rescued = false) {
  const p = locations.find((point) => point.id === id),
    story = guardianStories[id];
  if (!p || !story) throw new Error("Хранитель не найден.");
  if (rescued)
    return [
      line(p.name, story[2], id),
      line(
        p.name,
        "Моё воспоминание уже в вашем альбоме. Можете вернуться к нему или отправиться к следующему другу.",
        id,
      ),
    ];
  return [
    line(p.name, story[0], id),
    {
      ...line(p.name, "Поможете выбраться из тумана?", id),
      choices: [
        {
          label: "Да, мы тебя спасём!",
          next: [
            line(
              p.name,
              "Спасибо! У меня есть маленькое задание для вашей команды.",
              id,
            ),
          ],
        },
        {
          label: "Что поможет вернуть память?",
          next: [line(p.name, story[1], id)],
        },
      ],
    },
    line(p.name, missions[id], id),
    line(
      p.name,
      "Найдите мою настоящую бронзовую статую. После задания сохраните фото встречи — и туман вокруг меня рассеется!",
      id,
    ),
  ];
}
export function rescueDialogue(id, milestone = null) {
  const p = locations[id];
  const lines = [line(p.name, guardianStories[id][2], id)];
  if (milestone?.goal === 5)
    lines.push(
      line(
        "Забывайка",
        "Почему ваш альбом такой яркий? Мне казалось, в тумане всем спокойнее… Может быть, я ошибся?",
        "fog",
      ),
    );
  if (milestone?.goal === 12)
    lines.push(
      line(
        "Забывайка",
        "Вы сохранили столько встреч! А можно я тоже помогу? Кажется, мне больше не хочется прятать друзей.",
        "fog",
      ),
    );
  if (milestone?.goal === 24)
    lines.push(
      line(
        "Забывайка",
        "Теперь и у меня есть своё воспоминание — как вы помогли всем хранителям. Я больше не буду прятать город. Можно остаться маленьким облаком над Енисеем?",
        "fog",
      ),
      line(
        "Чтец",
        "Конечно! Красноярск снова сияет. А ваша команда сохранила целую историю добрых встреч.",
        9,
      ),
    );
  return lines;
}
